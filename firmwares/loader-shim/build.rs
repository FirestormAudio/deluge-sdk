use std::env;
use std::fs;
use std::path::PathBuf;

/// The boot slots' flash offsets (`deluge_image::slot::DELUGE`).
const SLOT_A: u32 = 0x01_0000;
const SLOT_B: u32 = 0x08_0000;
/// Where the payload starts in the slot (`src/main.rs`'s `PAYLOAD`): the shim gets the rest of
/// the first 4 KB after the slot's 256-byte header page.
const PAYLOAD: u32 = 0x1000;

fn main() {
    // The shim executes in place right after its slot's header page, so its memory layout
    // depends on the slot (rza1-rt's `link_xip.x` INCLUDEs `memory_xip.x`).
    println!("cargo:rerun-if-changed=build.rs");
    if env::var("CARGO_CFG_TARGET_OS").as_deref() != Ok("none") {
        return;
    }
    let slot = if env::var_os("CARGO_FEATURE_SLOT_B").is_some() {
        SLOT_B
    } else {
        SLOT_A
    };
    let memory = format!(
        "/* Generated by build.rs: the shim's flash (its slot, after the header page, up to the\n \
         * payload) and its RAM (the upper half of the data-retention RAM: clear of the boot-info\n \
         * word at 0x20000000 and of the loader it copies to 0x20020000). */\n\
         MEMORY {{\n\
         \x20   FLASH (rx)  : ORIGIN = {:#010x}, LENGTH = {:#x}\n\
         \x20   RAM   (rwx) : ORIGIN = 0x20010000, LENGTH = 0x10000\n\
         }}\n\
         PROGRAM_STACK_SIZE = 0x1000;\n\
         IRQ_STACK_SIZE     = 0x200;\n\
         FIQ_STACK_SIZE     = 0x200;\n\
         SVC_STACK_SIZE     = 0x200;\n\
         ABT_STACK_SIZE     = 0x200;\n\
         INTERNAL_RAM_END   = 0x20020000;\n",
        0x1800_0000 + slot + 0x100,
        PAYLOAD - 0x100,
    );
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    fs::write(out.join("memory_xip.x"), memory).unwrap();
    println!("cargo:rustc-link-search={}", out.display());
    println!("cargo:rustc-link-arg-bins=-Tlink_xip.x");
}

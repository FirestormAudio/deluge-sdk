#!/usr/bin/env python3
"""Generate rza1-hal's pin-function table from the RZ/A1L hardware manual's port chapter.

Reads the per-port "Pin Function (Pn)" tables (Tables 41.11-41.29) of
vendor/docs/rza1/rza1l-hw-manual/ch41-ports.md and writes
rza1-hal/src/gpio/rza1l_functions.rs: one `pin_function!` per (pin, signal) for the signals the
HAL's drivers take pins for (SCIF, RSPI, SDHI, IRQ0-7). Also checks that rza1-hal/src/gpio/pins.rs marks
exactly the pins with a port-mode output as `out`.

Each table's Input/Output header row gives its column layout (port mode, then alternative 1..N,
with N from 4 to 8 and some blank spare columns). The Markdown was extracted from the PDF, so a
row that lost or gained a cell would shift every later alternative: a row whose cell count differs
from its header, or that has a value in a blank column, is refused unless
rza1-hal/pins/rza1l-overrides.yaml resolves it, and a refused row naming a wanted signal fails the
run.

Usage (from rza1/): tools/gen-pins.py [--check]
  --check  regenerate and diff against the checked-in file; skips (exit 0) with a notice when the
           manual is absent.
"""

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MANUAL = ROOT / "vendor/docs/rza1/rza1l-hw-manual/ch41-ports.md"
OVERRIDES = ROOT / "rza1-hal/pins/rza1l-overrides.yaml"
OUT = ROOT / "rza1-hal/src/gpio/rza1l_functions.rs"
PINS_RS = ROOT / "rza1-hal/src/gpio/pins.rs"

# The instances the RZ/A1L has: SCIF0-4, RSPI0-2, SDHI0-1, IRQ0-7.
SIGNALS = [
    (re.compile(r"^TxD([0-4])$"), lambda m: ("crate::uart::TxPin", f"SCIF{m[1]}")),
    (re.compile(r"^RxD([0-4])$"), lambda m: ("crate::uart::RxPin", f"SCIF{m[1]}")),
    (re.compile(r"^RSPCK([0-2])$"), lambda m: ("crate::rspi::SckPin", f"RSPI{m[1]}")),
    (re.compile(r"^MOSI([0-2])$"), lambda m: ("crate::rspi::MosiPin", f"RSPI{m[1]}")),
    (re.compile(r"^MISO([0-2])$"), lambda m: ("crate::rspi::MisoPin", f"RSPI{m[1]}")),
    (re.compile(r"^SSL([0-2])0$"), lambda m: ("crate::rspi::SslPin", f"RSPI{m[1]}")),
    (re.compile(r"^SD_CLK_([01])$"), lambda m: ("crate::sdhi::ClkPin", f"SDHI{m[1]}")),
    (re.compile(r"^SD_CMD_([01])$"), lambda m: ("crate::sdhi::CmdPin", f"SDHI{m[1]}")),
    (re.compile(r"^SD_D([0-3])_([01])$"), lambda m: (f"crate::sdhi::D{m[1]}Pin", f"SDHI{m[2]}")),
    (re.compile(r"^SD_CD_([01])$"), lambda m: ("crate::sdhi::CdPin", f"SDHI{m[1]}")),
    (re.compile(r"^SD_WP_([01])$"), lambda m: ("crate::sdhi::WpPin", f"SDHI{m[1]}")),
    (re.compile(r"^IRQ([0-7])$"), lambda m: ("crate::exti::IrqPin", f"EXTI{m[1]}")),
]

HEADER = """\
// Generated by rza1/tools/gen-pins.py from the RZ/A1L hardware manual's port tables (ch41) and
// rza1/rza1-hal/pins/rza1l-overrides.yaml. Do not edit: regenerate.
"""


def wanted(signal):
    for pattern, make in SIGNALS:
        m = pattern.match(signal)
        if m:
            return make(m)
    return None


def clean(cell):
    cell = cell.replace("<br>", "").replace(" ", "")
    return re.sub(r"\*\d+", "", cell).strip()


def parse_manual(text):
    """{pin: (has_output, {alt: [signal, ...]} or None)}, and the refused rows' raw cells.

    Each table's `|**Input**|**Output**|...|` header row is its column map: every Input starts a
    group (group 0 is port mode, group k alternative k) and the Output after it joins that group.
    Some headers have blank spare columns; a data row must have the header's cell count, and a
    value in a blank column refuses the row.
    """
    pins, refused = {}, {}
    header = None
    for line in text.splitlines():
        if line.startswith("|") and "**Input**" in line:
            header = [clean(c).strip("*") for c in line.split("|")[1:-1]]
            continue
        m = re.match(r"^\|(P\d_\d+)\|", line)
        if not m or header is None:
            continue
        cells = [clean(c) for c in line.split("|")[1:-1]]
        pin = m[1]
        has_output = len(cells) > 1 and cells[1] == pin
        groups, ok = [], len(cells) == len(header)
        if ok:
            for label, cell in zip(header, cells):
                if label == "Input":
                    groups.append([cell])
                elif label == "Output" and groups:
                    groups[-1].append(cell)
                elif cell:
                    ok = False
        # A signal name split across two cells (`SD_D0|_1`) would be dropped silently: two adjacent
        # cells that only together name a wanted signal refuse the row.
        if ok and any(
            a and b and wanted(a + b) and not wanted(a) and not wanted(b)
            for a, b in zip(cells, cells[1:])
        ):
            ok = False
        if not ok:
            refused[pin] = cells
            pins[pin] = (has_output, None)
            continue
        table = {k: [c for c in group if c] for k, group in enumerate(groups) if k > 0}
        pins[pin] = (has_output, {k: v for k, v in table.items() if v})
    return pins, refused


def generate(text, overrides):
    pins, refused = parse_manual(text)
    errors, lines = [], []
    for pin, (_, table) in pins.items():
        if pin in overrides:
            table = {int(k): [v] for k, v in overrides[pin]["alternates"].items()}
        elif table is None:
            raw = refused[pin]
            joined = [a + b for a, b in zip(raw, raw[1:]) if a and b]
            if any(wanted(c) for c in raw + joined if c):
                errors.append(f"{pin}: {len(raw)} cells, names a wanted signal: {raw}")
            continue
        for alt, names in table.items():
            for name in names:
                w = wanted(name)
                if w:
                    trait, instance = w
                    lines.append(f"pin_function!({trait}, {instance}, {pin}, Alt{alt});")
    if errors:
        sys.exit("error: rows the overrides file must resolve:\n  " + "\n  ".join(errors))
    return HEADER + "\n" + "\n".join(sorted(lines)) + "\n", pins


def check_output_flags(pins):
    """pins.rs's `out`/`in` flags must match the tables' port-mode output column."""
    declared = dict(re.findall(r"(P\d_\d+) = \(\d+, \d+, (out|in)\)", PINS_RS.read_text()))
    bad = [
        f"{pin}: pins.rs says {declared.get(pin)}, the table says {'out' if out else 'in'}"
        for pin, (out, _) in sorted(pins.items())
        if declared.get(pin) != ("out" if out else "in")
    ]
    missing = sorted(set(declared) - set(pins))
    if bad or missing:
        sys.exit("error: pins.rs disagrees with the manual:\n  " + "\n  ".join(bad + missing))


def main():
    check = "--check" in sys.argv[1:]
    if not MANUAL.exists():
        if check:
            print(f"gen-pins: {MANUAL.relative_to(ROOT)} absent; skipping the pin-table check")
            return
        sys.exit(f"error: {MANUAL} not found")
    overrides = yaml.safe_load(OVERRIDES.read_text()) or {}
    out, pins = generate(MANUAL.read_text(), overrides)
    check_output_flags(pins)
    if check:
        if OUT.read_text() != out:
            sys.exit(f"error: {OUT.relative_to(ROOT)} is stale; run tools/gen-pins.py")
        print("gen-pins: rza1l_functions.rs matches the manual")
    else:
        OUT.write_text(out)
        print(f"gen-pins: wrote {OUT.relative_to(ROOT)} ({out.count('pin_function!')} entries)")


if __name__ == "__main__":
    main()
